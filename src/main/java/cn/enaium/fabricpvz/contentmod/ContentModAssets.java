package cn.enaium.fabricpvz.contentmod;

import java.awt.image.BufferedImage;
import java.io.IOException;
import java.io.InputStream;

import javax.imageio.ImageIO;

import cn.enaium.fabricpvz.portable.lawn.ImageID;
import cn.enaium.fabricpvz.portable.lawn.Resources;
import cn.enaium.fabricpvz.portable.pvzp.reanim.Reanimation;
import cn.enaium.fabricpvz.portable.sexy.SexyAppBase;
import cn.enaium.fabricpvz.portable.sexy.graphics.Image;
import cn.enaium.fabricpvz.portable.sexy.graphics.MemoryImage;

/**
 * The mod's own art: two seed-packet icons and the recoloured torso of the custom zombie.
 *
 * <p>All three PNGs are generated by {@code tools/generate_assets.py}, which recolours sprites of
 * the retail game (the player's own {@code main.pak}) and commits the result under this mod's
 * resources. They are loaded here, from the mod jar, through {@link ImageIO} and handed to the game
 * as {@link MemoryImage}s - the same image type the game itself loads its PNGs into.
 *
 * <h2>Where the packet art goes, and why</h2>
 *
 * <p>{@code PlantType.Builder#packetArt(int, int)} takes an {@code ImageID}, i.e. an index into
 * {@link Resources#gResources}. The game has no image id range reserved for mods, so the two slots
 * the mod uses are retail ids that <em>this port never reads</em> (verified by grepping the game for
 * the {@code ImageID} constants); they exist in the resource table, so the id is in range, and no
 * other draw call ever looks at them:
 *
 * <ul>
 *   <li>{@link ImageID#IMAGE_PEA_SPLATS} (218) - packet art of the Sniper Pea,</li>
 *   <li>{@link ImageID#IMAGE_POTATOMINE_PARTICLES} (226) - packet art of the Sun Orchid.</li>
 * </ul>
 *
 * <p>Both ids belong to the {@code LoadingImages} group, which the game's loading thread loads after
 * the mod's entry point runs, so an unambiguous installation point is needed: the mod installs its
 * packet art on {@code GameLifecycleEvents.INITIALIZED} and re-installs it after every resource
 * group extraction, which {@link cn.enaium.fabricpvz.contentmod.mixin.ResourcesMixin} hooks into
 * (the published API has no resource-reload event, so the mod supplies that one mixin itself), plus
 * once per gameplay tick as a safety net. {@link #packetArtBound()} reports whether both slots
 * currently hold the mod's images, and the end-to-end harness asserts exactly that.
 */
public final class ContentModAssets {

    /** Image id the Sniper Pea's seed packet draws its art from. */
    public static final int PACKET_IMAGE_SNIPER_PEA = ImageID.IMAGE_PEA_SPLATS;

    /** Image id the Sun Orchid's seed packet draws its art from. */
    public static final int PACKET_IMAGE_SUN_ORCHID = ImageID.IMAGE_POTATOMINE_PARTICLES;

    /**
     * Reanimation track the recoloured torso replaces. {@code Zombie_body} is the torso image of the
     * retail {@code Zombie.reanim}, so the override keeps every transform and animation the retail
     * zombie has and only swaps the artwork.
     */
    public static final String ZOMBIE_TORSO_TRACK = "Zombie_body";

    private static final String SNIPER_PEA_PACKET_FILE = "packet_sniper_pea.png";
    private static final String SUN_ORCHID_PACKET_FILE = "packet_sun_orchid.png";
    private static final String ZOMBIE_TORSO_FILE = "zombie_torso.png";

    private static final String TEXTURE_ROOT = "/assets/pvz-content-mod/textures/";

    /** How often the packet art has been (re-)installed. */
    public static int packetArtInstalls;

    /** How often the packet art was re-applied after a resource group load. */
    public static int reapplyCalls;

    /** How often {@link cn.enaium.fabricpvz.contentmod.mixin.ResourcesMixin} ran; 0 means it did not apply. */
    public static int mixinCallbacks;

    /** Last asset loading problem, empty when every asset loaded. */
    public static String loadError = "";

    private static Image sniperPeaPacket;
    private static Image sunOrchidPacket;
    private static Image zombieTorso;

    private ContentModAssets() {
    }

    /**
     * Loads the mod's images and binds the packet art into the game's resource table. Called from the
     * mod's {@code ModInitializer} and from the {@code GameLifecycleEvents.INITIALIZED} listener; the
     * images belong to the running application (they register themselves with it), so nothing happens
     * while there is no application yet - i.e. at mod-init time.
     */
    public static synchronized void installPacketArt() {
        if (SexyAppBase.current == null) {
            return;
        }

        sniperPeaPacket = loadCached(sniperPeaPacket, SNIPER_PEA_PACKET_FILE);
        sunOrchidPacket = loadCached(sunOrchidPacket, SUN_ORCHID_PACKET_FILE);
        packetArtInstalls++;
        reapplyOverrides();
    }

    /**
     * Puts the mod's packet art back into the two image slots. Idempotent and cheap: a slot that
     * already holds the mod's image is left untouched, and the first call after the images are
     * available (once the game is running) does the loading.
     */
    public static void reapplyOverrides() {
        reapplyCalls++;

        if ((sniperPeaPacket == null || sunOrchidPacket == null) && SexyAppBase.current != null) {
            installPacketArt();
            return;
        }

        if (sniperPeaPacket != null && Resources.getImageById(PACKET_IMAGE_SNIPER_PEA) != sniperPeaPacket) {
            Resources.setImageById(PACKET_IMAGE_SNIPER_PEA, sniperPeaPacket);
        }
        if (sunOrchidPacket != null && Resources.getImageById(PACKET_IMAGE_SUN_ORCHID) != sunOrchidPacket) {
            Resources.setImageById(PACKET_IMAGE_SUN_ORCHID, sunOrchidPacket);
        }
    }

    /** Called by {@code ResourcesMixin} for every resource group extraction; diagnostics only. */
    public static void noteMixinCallback() {
        mixinCallbacks++;
    }

    /** @return whether both packet slots currently hold the mod's own images. */
    public static boolean packetArtBound() {
        return sniperPeaPacket != null && Resources.getImageById(PACKET_IMAGE_SNIPER_PEA) == sniperPeaPacket
                && sunOrchidPacket != null && Resources.getImageById(PACKET_IMAGE_SUN_ORCHID) == sunOrchidPacket;
    }

    /** @param theSlot one of the two {@code PACKET_IMAGE_*} ids @return the mod's image for it */
    public static Image packetImageFor(int theSlot) {
        if (theSlot == PACKET_IMAGE_SNIPER_PEA) {
            sniperPeaPacket = loadCached(sniperPeaPacket, SNIPER_PEA_PACKET_FILE);
            return sniperPeaPacket;
        }
        if (theSlot == PACKET_IMAGE_SUN_ORCHID) {
            sunOrchidPacket = loadCached(sunOrchidPacket, SUN_ORCHID_PACKET_FILE);
            return sunOrchidPacket;
        }
        return null;
    }

    /** @return the recoloured zombie torso, loaded from the mod jar on first use. */
    public static Image zombieTorsoImage() {
        if (zombieTorso == null && SexyAppBase.current != null) {
            zombieTorso = load(ZOMBIE_TORSO_FILE);
        }
        return zombieTorso;
    }

    /**
     * Applies the recoloured torso to one zombie reanimation: the retail torso image is replaced, so
     * the zombie keeps all of its animation and only changes colour.
     *
     * @param theBodyReanim the zombie's body reanimation, {@code null} when the game has none
     * @return whether the override was applied
     */
    public static boolean applyZombieTorso(Reanimation theBodyReanim) {
        Image aTorso = zombieTorsoImage();
        if (theBodyReanim == null || theBodyReanim.mTrackInstances == null || aTorso == null) {
            // A reanimation without track instances (no retail .reanim data loaded) cannot carry an
            // override; the zombie then simply keeps the retail torso.
            return false;
        }
        theBodyReanim.setImageOverride(ZOMBIE_TORSO_TRACK, aTorso);
        return true;
    }

    /**
     * Reads a PNG that ships inside the mod jar.
     *
     * @param theFile file name under {@code assets/pvz-content-mod/textures/}
     * @return the image, or {@code null} when it is missing or unreadable ({@link #loadError} says why)
     */
    public static Image load(String theFile) {
        String aPath = TEXTURE_ROOT + theFile;
        try (InputStream aStream = ContentModAssets.class.getResourceAsStream(aPath)) {
            if (aStream == null) {
                loadError = "mod asset missing from the jar: " + aPath;
                return null;
            }

            BufferedImage aBuffered = ImageIO.read(aStream);
            if (aBuffered == null) {
                loadError = "not a readable PNG: " + aPath;
                return null;
            }

            int aWidth = aBuffered.getWidth();
            int aHeight = aBuffered.getHeight();
            int[] aBits = new int[aWidth * aHeight];
            aBuffered.getRGB(0, 0, aWidth, aHeight, aBits, 0, aWidth);

            MemoryImage aImage = new MemoryImage(SexyAppBase.current);
            aImage.setBits(aBits, aWidth, aHeight, false);
            aImage.setImageMode(true, true);
            return aImage;
        } catch (IOException | RuntimeException e) {
            loadError = aPath + ": " + e;
            return null;
        }
    }

    private static Image loadCached(Image theImage, String theFile) {
        return theImage != null ? theImage : load(theFile);
    }
}
